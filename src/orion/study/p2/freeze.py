"""Freeze, load and verify the ORION-P2 offline complete-gold suite.

The suite is frozen *before* any system is configured against it. That ordering
is the only thing that makes the world an honest measuring instrument: once a
candidate has been tuned against a corpus, the corpus is no longer independent of
the candidate, and no hash committed afterwards can undo that.

Regeneration from `FROZEN_SEED` on a clean checkout must reproduce the committed
`suite_fingerprint` exactly. `verify` is what says so, and it is what the tests
call — including across a process boundary, since a suite that only reproduces
inside one interpreter is not reproducible at all.

Run `python3 -m orion.study.p2.freeze --write` to regenerate the artifact, or
with no arguments to verify the committed one.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .cases import (
    TASK_SCHEMA_VERSION,
    DiscoveryTask,
    build_tasks,
    suite_fingerprint,
    task_from_json,
)
from .corpus import (
    CORPUS_SCHEMA_VERSION,
    DiscoveryWorld,
    build_world,
    canonical_bytes,
    sha256_digest,
    world_from_json,
)

FROZEN_SEED = 20260816
MANIFEST_SCHEMA_VERSION = "orion.p2.offline-gold-manifest.v1"

PROVENANCE = (
    "Fully synthetic. Generated by src/orion/study/p2/corpus.py from the recorded "
    "seed; contains no third-party text, metadata or identifiers, and so carries "
    "no third-party licence encumbrance. Redistributable on the repository's own "
    "terms; no separate licence is asserted here."
)

DEFAULT_ROOT = (
    Path(__file__).resolve().parents[4]
    / "papers"
    / "orion-12-open-world-scientific-discovery"
    / "evidence"
    / "offline_gold"
)

TOPICS_FILE = "topics.json"
MANIFEST_FILE = "MANIFEST.json"
WORLD_SHARD_PREFIX = "world-"
TASKS_SHARD_PREFIX = "tasks-"
MAX_FILE_BYTES = 1_000_000
SHARD_TARGET_BYTES = 700_000


def _shard_name(prefix: str, index: int) -> str:
    return f"{prefix}{index:03d}.json"


def _slices(items: list[Any], count: int) -> list[list[Any]]:
    """Split into `count` contiguous near-equal chunks, order preserved."""

    if count < 1:
        raise ValueError("a shard count of at least one is required")
    total = len(items)
    base, extra = divmod(total, count)
    chunks: list[list[Any]] = []
    start = 0
    for position in range(count):
        size = base + (1 if position < extra else 0)
        chunks.append(items[start : start + size])
        start += size
    return chunks


def _shard_payloads(
    items: list[Any],
    *,
    field: str,
    header: dict[str, Any],
    prefix: str,
) -> dict[str, dict[str, Any]]:
    """Pack `items` into as few shards as keep each one under the target size."""

    count = 1
    while True:
        chunks = _slices(items, count)
        payloads = {
            _shard_name(prefix, index): {
                **header,
                "shard_index": index,
                "shard_count": count,
                field: chunk,
            }
            for index, chunk in enumerate(chunks)
        }
        largest = max(
            len(_dump(payload).encode("utf-8")) for payload in payloads.values()
        )
        if largest <= SHARD_TARGET_BYTES or count >= len(items):
            return payloads
        count += 1


@dataclass(frozen=True)
class FrozenSuite:
    world: DiscoveryWorld
    tasks: tuple[DiscoveryTask, ...]

    @property
    def fingerprint(self) -> str:
        return suite_fingerprint(self.world, self.tasks)


def build_suite(seed: int = FROZEN_SEED) -> FrozenSuite:
    world = build_world(seed)
    return FrozenSuite(world=world, tasks=build_tasks(world))


def _dump(payload: Any) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n"


def write_suite(root: Path = DEFAULT_ROOT, *, seed: int = FROZEN_SEED) -> dict[str, Any]:
    """Write the frozen suite and its manifest. Returns the manifest."""

    suite = build_suite(seed)
    root.mkdir(parents=True, exist_ok=True)

    world_json = suite.world.as_json()
    files: dict[str, dict[str, Any]] = {
        TOPICS_FILE: {
            "schema_version": CORPUS_SCHEMA_VERSION,
            "seed": seed,
            "topics": world_json["topics"],
        }
    }
    files.update(
        _shard_payloads(
            list(world_json["documents"]),
            field="documents",
            header={"schema_version": CORPUS_SCHEMA_VERSION, "seed": seed},
            prefix=WORLD_SHARD_PREFIX,
        )
    )
    files.update(
        _shard_payloads(
            [task.as_json() for task in suite.tasks],
            field="tasks",
            header={"schema_version": TASK_SCHEMA_VERSION},
            prefix=TASKS_SHARD_PREFIX,
        )
    )

    world_shards = sorted(
        name for name in files if name.startswith(WORLD_SHARD_PREFIX)
    )
    task_shards = sorted(name for name in files if name.startswith(TASKS_SHARD_PREFIX))

    for existing in sorted(root.glob("*.json")):
        if existing.name not in files and existing.name != MANIFEST_FILE:
            existing.unlink()

    for name, payload in sorted(files.items()):
        text = _dump(payload)
        size = len(text.encode("utf-8"))
        if size > MAX_FILE_BYTES:
            raise ValueError(
                f"{name} is {size} bytes, above the {MAX_FILE_BYTES}-byte shard ceiling; "
                "the shard packer failed to split it small enough"
            )
        (root / name).write_text(text, encoding="utf-8")

    manifest = {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "corpus_schema_version": CORPUS_SCHEMA_VERSION,
        "task_schema_version": TASK_SCHEMA_VERSION,
        "seed": seed,
        "suite_fingerprint": suite.fingerprint,
        "world_content_hash": suite.world.content_hash,
        "document_count": len(suite.world.documents),
        "topic_count": len(suite.world.topics),
        "task_count": len(suite.tasks),
        "shards": {
            "topics": [TOPICS_FILE],
            "world": world_shards,
            "tasks": task_shards,
        },
        "max_file_bytes": MAX_FILE_BYTES,
        "files": {
            name: {
                "sha256": sha256_digest(payload),
                "bytes": len(_dump(payload).encode("utf-8")),
            }
            for name, payload in sorted(files.items())
        },
        "provenance": PROVENANCE,
        "regenerate": "python3 -m orion.study.p2.freeze --write",
        "frozen_before_any_system_configured": True,
    }
    (root / MANIFEST_FILE).write_text(_dump(manifest), encoding="utf-8")
    return manifest


def _read_shards(root: Path, prefix: str, field: str) -> list[Any]:
    """Concatenate a sharded collection, refusing any incomplete shard set."""

    shards: dict[int, dict[str, Any]] = {}
    declared: set[int] = set()
    for path in sorted(root.glob(f"{prefix}*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        index = int(payload["shard_index"])
        if index in shards:
            raise ValueError(f"duplicate shard index {index} for {prefix}*")
        shards[index] = payload
        declared.add(int(payload["shard_count"]))
    if not shards:
        raise FileNotFoundError(f"no shards found for {prefix}* under {root}")
    if len(declared) != 1:
        raise ValueError(f"{prefix}* shards disagree on shard_count: {sorted(declared)}")
    count = declared.pop()
    missing = sorted(set(range(count)) - set(shards))
    if missing:
        raise ValueError(f"{prefix}* is missing shard indices {missing}")
    if len(shards) != count:
        raise ValueError(f"{prefix}* has {len(shards)} shards but declares {count}")
    items: list[Any] = []
    for index in range(count):
        items.extend(shards[index][field])
    return items


def load_suite(root: Path = DEFAULT_ROOT) -> FrozenSuite:
    """Load the committed suite from disk without regenerating it."""

    topics_payload = json.loads((root / TOPICS_FILE).read_text(encoding="utf-8"))
    world = world_from_json(
        {
            "schema_version": topics_payload["schema_version"],
            "seed": topics_payload["seed"],
            "topics": topics_payload["topics"],
            "documents": _read_shards(root, WORLD_SHARD_PREFIX, "documents"),
        }
    )
    tasks = tuple(
        sorted(
            (
                task_from_json(item)
                for item in _read_shards(root, TASKS_SHARD_PREFIX, "tasks")
            ),
            key=lambda item: item.task_id,
        )
    )
    return FrozenSuite(world=world, tasks=tasks)


def load_manifest(root: Path = DEFAULT_ROOT) -> dict[str, Any]:
    return json.loads((root / MANIFEST_FILE).read_text(encoding="utf-8"))


@dataclass(frozen=True)
class VerificationReport:
    ok: bool
    problems: tuple[str, ...]
    regenerated_fingerprint: str
    committed_fingerprint: str
    loaded_fingerprint: str


def verify(root: Path = DEFAULT_ROOT) -> VerificationReport:
    """Check that seed, committed bytes and manifest all agree without crashing."""

    problems: list[str] = []
    regenerated = build_suite(FROZEN_SEED)
    regenerated_fingerprint = regenerated.fingerprint

    try:
        manifest = load_manifest(root)
    except (OSError, json.JSONDecodeError, TypeError, ValueError, KeyError) as exc:
        return VerificationReport(
            ok=False,
            problems=(f"unable to load frozen manifest: {type(exc).__name__}: {exc}",),
            regenerated_fingerprint=regenerated_fingerprint,
            committed_fingerprint="",
            loaded_fingerprint="",
        )

    committed_fingerprint = str(manifest.get("suite_fingerprint", ""))

    loaded: FrozenSuite | None
    try:
        loaded = load_suite(root)
        loaded_fingerprint = loaded.fingerprint
    except (OSError, json.JSONDecodeError, TypeError, ValueError, KeyError) as exc:
        loaded = None
        loaded_fingerprint = ""
        problems.append(f"unable to load committed suite: {type(exc).__name__}: {exc}")

    if manifest.get("seed") != FROZEN_SEED:
        problems.append(f"manifest seed {manifest.get('seed')!r} != FROZEN_SEED {FROZEN_SEED}")
    if regenerated_fingerprint != committed_fingerprint:
        problems.append("regenerated suite fingerprint does not match the manifest")
    if loaded is not None and loaded_fingerprint != committed_fingerprint:
        problems.append("committed suite files do not match the manifest fingerprint")
    if regenerated.world.content_hash != str(manifest.get("world_content_hash", "")):
        problems.append("regenerated world content hash does not match the manifest")

    recorded_files = manifest.get("files", {})
    if not isinstance(recorded_files, dict):
        problems.append("manifest files must be an object")
        recorded_files = {}
    for name, expected in sorted(recorded_files.items()):
        path = root / name
        if not path.is_file():
            problems.append(f"missing frozen file: {name}")
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"unable to parse frozen file {name}: {type(exc).__name__}: {exc}")
            continue
        if not isinstance(expected, dict):
            problems.append(f"manifest file record for {name} must be an object")
            continue
        if sha256_digest(payload) != expected.get("sha256"):
            problems.append(f"{name} content hash does not match the manifest")
        size = len(_dump(payload).encode("utf-8"))
        if size > MAX_FILE_BYTES:
            problems.append(f"{name} is {size} bytes, above the {MAX_FILE_BYTES}-byte ceiling")

    on_disk = {path.name for path in root.glob("*.json")} - {MANIFEST_FILE}
    unrecorded = sorted(on_disk - set(recorded_files))
    if unrecorded:
        problems.append(f"files present but not recorded in the manifest: {unrecorded}")

    shards = manifest.get("shards", {})
    if not isinstance(shards, dict):
        problems.append("manifest shards must be an object")
        shards = {}
    for kind, prefix in (("world", WORLD_SHARD_PREFIX), ("tasks", TASKS_SHARD_PREFIX)):
        declared_raw = shards.get(kind, ())
        declared = list(declared_raw) if isinstance(declared_raw, (list, tuple)) else []
        found = sorted(path.name for path in root.glob(f"{prefix}*.json"))
        if declared != found:
            problems.append(
                f"{kind} shard set on disk {found} does not match the manifest {declared}"
            )

    if loaded is not None:
        for label, key, actual in (
            ("document_count", "document_count", len(loaded.world.documents)),
            ("topic_count", "topic_count", len(loaded.world.topics)),
            ("task_count", "task_count", len(loaded.tasks)),
        ):
            if manifest.get(key) != actual:
                problems.append(f"manifest {label} {manifest.get(key)!r} != loaded {actual}")

    return VerificationReport(
        ok=not problems,
        problems=tuple(problems),
        regenerated_fingerprint=regenerated_fingerprint,
        committed_fingerprint=committed_fingerprint,
        loaded_fingerprint=loaded_fingerprint,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the frozen suite")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument(
        "--print-fingerprint",
        action="store_true",
        help="print only the regenerated suite fingerprint and exit",
    )
    args = parser.parse_args(argv)

    if args.print_fingerprint:
        sys.stdout.write(build_suite(FROZEN_SEED).fingerprint + "\n")
        return 0
    if args.write:
        manifest = write_suite(args.root)
        sys.stdout.write(canonical_bytes(manifest).decode("utf-8") + "\n")
        return 0

    report = verify(args.root)
    for problem in report.problems:
        sys.stderr.write(f"FROZEN SUITE PROBLEM: {problem}\n")
    sys.stdout.write(f"suite_fingerprint={report.regenerated_fingerprint}\n")
    return 0 if report.ok else 1


